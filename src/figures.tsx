// --- putting one on the page --------------------------------------------------

/**
 * A technology, shown: the photograph of the real thing, the diagram of how it
 * works, and the numbered words for the diagram's pins.
 *
 * The photograph goes first because it answers "what am I even looking at",
 * which is the question a diagram cannot answer, and the diagram answers "and
 * how does that do anything", which is the question a photograph cannot.
 */
export function TechFigure({
  id,
  steps,
  photo,
  compact,
  photoOnly,
}: {
  id: string
  steps?: string[]
  photo?: Photo
  compact?: boolean
  /**
   * The photograph on its own.
   *
   * The dialogue player uses this: mid-scene, a reader wants to know what the
   * thing looks like, and a schematic with numbered pins is a thing to study
   * rather than a thing to glance at. The diagram lives in the glossary, one
   * click away, where studying it is the point.
   */
  photoOnly?: boolean
}) {
  const fig = photoOnly ? undefined : figureFor(id)
  if (!fig && !photo) return null
  return (
    <figure className={`figure${compact ? ' figure--compact' : ''}${photoOnly ? ' figure--photo' : ''}`}>
      {photo && (
        <div className="figure__photo">
          <img src={photo.src} alt="" loading="lazy" />
          <p className="figure__credit">
            <a href={photo.page} target="_blank" rel="noreferrer noopener">
              {photo.credit}
            </a>
            <span>{photo.license}</span>
          </p>
        </div>
      )}
      {fig && (
        <div className="figure__plate">
          <svg viewBox={`0 0 ${W} ${H}`} className="figure__svg" role="img" aria-hidden>
            {fig.draw()}
          </svg>
        </div>
      )}
      {/* A sibling of the drawing rather than a child of it, so a caller with
          room to spare can stand the walk-through beside the diagram instead
          of under it. The dialogue plate does exactly that. */}
      {fig && steps && steps.length > 0 && (
        <ol className="figure__steps">
          {steps.map((step, i) => (
            <li key={i}>{step}</li>
          ))}
        </ol>
      )}
    </figure>
  )
}
