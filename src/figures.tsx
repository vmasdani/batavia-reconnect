/**
 * One drawn diagram per technology, and the photograph beside it.
 *
 * The glossary could already say what a thing is in a sentence, and a sentence
 * is not enough. A telephone explained in words is a list of nouns; a telephone
 * drawn as a loop — voice, diaphragm, carbon, current, wire, magnet, diaphragm,
 * voice — is a thing you can follow with a finger and never forget. That is the
 * whole reason this file exists, and it is why every diagram here is a *path a
 * signal takes*, not a picture of an object sitting still.
 *
 * Drawn in code, for the same reasons `backdrops.tsx` and `icons.tsx` are: they
 * inherit the palette, they cost nothing to ship, and a schematic is repeating
 * structure — coils, poles, jacks, cores, dies — which is steadier written as a
 * loop than drawn by hand.
 *
 * **No words live in the SVG.** Every diagram places numbered pins, and the
 * words for those pins come from the glossary entry, which means they translate
 * with everything else. A diagram declares how many pins it draws and
 * `check:script` refuses a term whose step list is a different length, so a new
 * translation cannot silently leave a pin unlabelled.
 *
 * The photograph is separate and optional: `photos.ts` is generated by
 * `npm run fetch:photos` from Wikipedia, and a term with no usable photo simply
 * shows the diagram, which is the half that does the teaching anyway.
 */

import type { ReactNode } from 'react'
import type { Photo } from './photos'

// --- the shared frame --------------------------------------------------------

/**
 * Every diagram is drawn in this box and cropped by nothing, so a row of them
 * lines up and a reader learns where to look once.
 */
const W = 340
const H = 168

/** Flat tones, matching the backdrops: far structure, near structure, the one hot accent. */
const LINE = 'var(--fig-line)'
const FILL = 'var(--fig-fill)'
const EDGE = 'var(--fig-edge)'
const HOT = 'var(--fig-hot)'
const PIN = 'var(--fig-pin)'

const range = (n: number) => Array.from({ length: n }, (_, i) => i)

// --- primitives --------------------------------------------------------------

/** A labelled block: anything with an inside that the diagram does not open up. */
const Box = ({ x, y, w, h, r = 3 }: { x: number; y: number; w: number; h: number; r?: number }) => (
  <rect x={x} y={y} width={w} height={h} rx={r} fill={FILL} stroke={EDGE} strokeWidth="1.4" />
)

/** A conductor, or any path a signal travels. Dashed where the path is through air. */
const Wire = ({ d, hot, dash }: { d: string; hot?: boolean; dash?: boolean }) => (
  <path
    d={d}
    fill="none"
    stroke={hot ? HOT : LINE}
    strokeWidth={hot ? 1.8 : 1.4}
    strokeDasharray={dash ? '4 4' : undefined}
    strokeLinecap="round"
  />
)

/** An arrowhead on a wire, pointing the way the signal actually goes. */
const Tip = ({ x, y, a = 0, hot }: { x: number; y: number; a?: number; hot?: boolean }) => (
  <path
    d="M0 0 L-6 -3.4 L-6 3.4 Z"
    fill={hot ? HOT : LINE}
    transform={`translate(${x} ${y}) rotate(${a})`}
  />
)

/**
 * A numbered pin.
 *
 * The number is the one exception to the no-words rule, because a digit reads
 * the same in both languages and the alternative — leader lines to a caption —
 * needs twice the room and half as clear.
 */
const Pin = ({ n, x, y }: { n: number; x: number; y: number }) => (
  <g>
    <circle cx={x} cy={y} r="8.5" fill="var(--fig-pin-bg)" stroke={PIN} strokeWidth="1.3" />
    <text
      x={x}
      y={y + 3.6}
      textAnchor="middle"
      fontSize="10"
      fontWeight="700"
      fill={PIN}
      fontFamily="inherit"
    >
      {n}
    </text>
  </g>
)

/** A coil of wire seen from the side, `turns` humps long. */
const Coil = ({ x, y, turns, w = 7, h = 9 }: { x: number; y: number; turns: number; w?: number; h?: number }) => (
  <path
    d={`M${x} ${y} ` + range(turns).map(() => `q ${w / 2} ${-h} ${w} 0`).join(' ')}
    fill="none"
    stroke={LINE}
    strokeWidth="1.6"
  />
)

/** A person, from the side, small. Everything in Era 0 is a person. */
const Body = ({ x, y, s = 1 }: { x: number; y: number; s?: number }) => (
  <g transform={`translate(${x} ${y}) scale(${s})`} stroke={LINE} strokeWidth="1.5" fill="none">
    <circle cx="0" cy="-16" r="3.6" fill={LINE} stroke="none" />
    <path d="M0 -12 V-3" />
    <path d="M-4 -9 L4 -7 M0 -3 L-4 4 M0 -3 L4 4" />
  </g>
)

/** Ground, or the sea, or whatever is under the diagram. */
const Ground = ({ y = H - 18 }: { y?: number }) => (
  <path d={`M0 ${y} H${W}`} stroke={EDGE} strokeWidth="1.2" />
)

/** A hill, because half of Era 0 is about what a hill can see. */
const Hill = ({ x, w, h, base = H - 18 }: { x: number; w: number; h: number; base?: number }) => (
  <path d={`M${x} ${base} Q${x + w / 2} ${base - h} ${x + w} ${base} Z`} fill={FILL} stroke={EDGE} strokeWidth="1.2" />
)

/** A radiating wave: `n` arcs stepping outward from a point. */
const Waves = ({ x, y, n, from = 10, gap = 9, a = 55 }: { x: number; y: number; n: number; from?: number; gap?: number; a?: number }) => (
  <g fill="none" stroke={HOT} strokeWidth="1.3" opacity="0.85">
    {range(n).map((i) => {
      const r = from + i * gap
      const rad = (a * Math.PI) / 180
      return (
        <path
          key={i}
          d={`M${x + r * Math.cos(-rad)} ${y + r * Math.sin(-rad)} A${r} ${r} 0 0 1 ${x + r * Math.cos(rad)} ${y + r * Math.sin(rad)}`}
        />
      )
    })}
  </g>
)

/** A sine, `cycles` long, drawn as one path so it can be clipped or dashed. */
const sine = (x: number, y: number, len: number, cycles: number, amp: number) => {
  const step = len / (cycles * 2)
  let d = `M${x} ${y}`
  for (let i = 0; i < cycles * 2; i++) {
    d += ` q ${step / 2} ${i % 2 ? amp : -amp} ${step} 0`
  }
  return d
}

/** A battery cell: long plate, short plate. */
const Cell = ({ x, y }: { x: number; y: number }) => (
  <g stroke={LINE} strokeWidth="1.5">
    <path d={`M${x} ${y - 8} V${y + 8}`} />
    <path d={`M${x + 5} ${y - 4} V${y + 4}`} strokeWidth="3" />
  </g>
)

// --- the diagrams ------------------------------------------------------------

/**
 * A diagram and the number of pins it draws.
 *
 * `pins` is the contract with the glossary: a term whose `steps` list is not
 * exactly this long is a bug, and `check:script` says so by name.
 */
export interface Figure {
  pins: number
  draw: () => ReactNode
}

const FIGURES: Record<string, Figure> = {}
const figure = (id: string, pins: number, draw: () => ReactNode) => {
  FIGURES[id] = { pins, draw }
}

export const figureFor = (id: string): Figure | undefined => FIGURES[id]

